import { randomBytes } from "node:crypto";
import type { TaigaClient } from "./client.js";

// Persistent entity identity. Task, User Story, Epic and Issue carry a text custom attribute named `UUID` holding a UUIDv7 that the MCP
// generates when it creates the entity (or initialize_project fills it later). It is write-once for MCP operations; `#ref` stays a human convenience.
// This module is the ONLY place that creates, finds, generates or assigns that value: tools call `withUuid`, nothing else.
// Sprint/Milestone are out of scope: Taiga exposes no custom attributes for milestones (GET /milestone-custom-attributes is 404).

export const UUID_ATTRIBUTE = "UUID";
// The name belongs to the identity subsystem; trivial variants (`uuid`, ` UUID `) are reserved too so no parallel identity is created by accident.
export const isReservedName = (name: unknown) => typeof name === "string" && name.trim().toLowerCase() === "uuid";
export class IdentityIntegrityError extends Error { constructor(message: string) { super(message); this.name = "IdentityIntegrityError"; } }
export type IdentityKind = "task" | "userstory" | "epic" | "issue";

export const IDENTITY: Record<IdentityKind, { definitions: string; values: string; entities: string }> = {
  task: { definitions: "task-custom-attributes", values: "tasks/custom-attributes-values", entities: "tasks" },
  userstory: { definitions: "userstory-custom-attributes", values: "userstories/custom-attributes-values", entities: "userstories" },
  epic: { definitions: "epic-custom-attributes", values: "epics/custom-attributes-values", entities: "epics" },
  issue: { definitions: "issue-custom-attributes", values: "issues/custom-attributes-values", entities: "issues" },
};

// Only a real UUIDv7 (version nibble 7, RFC 9562 variant 10xx) counts as a valid identity.
export const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

// RFC 9562 UUIDv7: 48-bit Unix ms timestamp, version 7, variant 10, 74 random bits.
export function uuidv7(now: number = Date.now(), rnd: Uint8Array = randomBytes(10)): string {
  const b = new Uint8Array(16);
  let t = BigInt(now);
  for (let i = 5; i >= 0; i--) { b[i] = Number(t & 0xffn); t >>= 8n; }
  b.set(rnd.subarray(0, 10), 6);
  b[6] = (b[6] & 0x0f) | 0x70;
  b[8] = (b[8] & 0x3f) | 0x80;
  const h = Buffer.from(b).toString("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

interface Definition { id: number; name: string }

// Attribute definitions are per project and keyed by id: always resolve the `UUID` attribute by NAME inside the target project, and
// ALWAYS from Taiga (no cache): the definitions can be changed from the UI/REST at any time and identity must never rest on a stale id.
// zero -> undefined; exactly one -> its id; more than one is an integrity error (never pick one arbitrarily).
export async function uuidAttributeId(client: TaigaClient, kind: IdentityKind, project: number, create: boolean): Promise<number | undefined> {
  const find = async () => {
    const defs = (await client.get(`/${IDENTITY[kind].definitions}`, { project })) as Definition[];
    const hits = Array.isArray(defs) ? defs.filter((d) => isReservedName(d.name)) : [];
    if (hits.length > 1) throw new IdentityIntegrityError(`integrity error: project ${project} has ${hits.length} "${UUID_ATTRIBUTE}" custom attribute definitions for ${kind} (ids ${hits.map((h) => h.id).join(", ")}); remove the duplicates by hand, nothing was chosen or written`);
    return hits[0]?.id;
  };
  const found = await find();
  if (found !== undefined || !create) return found;
  let created: Definition | undefined;
  try {
    created = (await client.post(`/${IDENTITY[kind].definitions}`, { project, name: UUID_ATTRIBUTE, type: "text", description: "Persistent entity identity (UUIDv7). Generated by the Taiga MCP; write-once." })) as Definition;
  } catch (e) {
    if (e instanceof IdentityIntegrityError) throw e;
    const other = await find(); // lost a creation race on the unique (project, name): the other writer's definition is the one
    if (other === undefined) throw e;
    return other;
  }
  // Never assume the creation left exactly one definition: read the state again (concurrent creators / different spellings).
  const after = await find();
  if (after !== created?.id) throw new IdentityIntegrityError(`integrity error: after creating the "${UUID_ATTRIBUTE}" definition for ${kind} in project ${project} the definitions are not exactly the one created (found ${after ?? "none"}, created ${created?.id}); nothing was written`);
  return after;
}

export interface UuidResult { uuid: string | null; assigned: boolean; invalid_existing?: boolean }

// Idempotent and non-destructive: an entity that already has a value keeps it byte for byte; only the UUID attribute is ever written
// (the other attribute values are sent back unchanged because the values endpoint takes the whole map plus its version).
export async function ensureUuid(client: TaigaClient, kind: IdentityKind, entity: { id: number; project: number }): Promise<UuidResult> {
  const attr = (await uuidAttributeId(client, kind, entity.project, true))!;
  const current = (await client.get(`/${IDENTITY[kind].values}/${entity.id}`)) as { version: number; attributes_values?: Record<string, string> };
  const existing = current.attributes_values?.[String(attr)];
  if (existing !== undefined && existing !== null && existing !== "") return UUID_RE.test(existing) ? { uuid: existing, assigned: false } : { uuid: null, assigned: false, invalid_existing: true };
  const uuid = uuidv7();
  // The definition may have changed since it was resolved: confirm it is still the single UUID definition immediately before writing.
  if ((await uuidAttributeId(client, kind, entity.project, false)) !== attr) throw new IdentityIntegrityError(`integrity error: the "${UUID_ATTRIBUTE}" definition for ${kind} in project ${entity.project} changed while assigning; nothing was written`);
  try {
    await client.patch(`/${IDENTITY[kind].values}/${entity.id}`, { attributes_values: { ...(current.attributes_values ?? {}), [String(attr)]: uuid }, version: current.version });
  } catch (e) {
    // A concurrent writer (version conflict) may have just assigned it: if a valid UUID is there now, that one wins and nothing is overwritten.
    const now = ((await client.get(`/${IDENTITY[kind].values}/${entity.id}`)) as { attributes_values?: Record<string, string> }).attributes_values?.[String(attr)];
    if (now && UUID_RE.test(now)) return { uuid: now, assigned: false };
    throw e;
  }
  // Read-back: "assigned" means the value is really there, not that the PATCH answered.
  const back = ((await client.get(`/${IDENTITY[kind].values}/${entity.id}`)) as { attributes_values?: Record<string, string> }).attributes_values?.[String(attr)];
  if (back !== uuid) throw new Error(`read-back failed: the UUID written for ${kind} ${entity.id} is not what Taiga now holds`);
  return { uuid, assigned: true };
}

// Creation hook used by every create tool. The entity already exists and cannot be rolled back, so an identity failure is reported
// in the result (`uuid: null`, `uuid_error`) and repaired later by taiga_uuid_initialize_project instead of failing the creation.
export async function withUuid<T>(client: TaigaClient, kind: IdentityKind, created: T): Promise<T> {
  if (Array.isArray(created)) {
    const out = [];
    for (const c of created) out.push(await withUuid(client, kind, c));
    return out as T;
  }
  const e = created as { id?: number; project?: number } | null;
  if (!e || typeof e !== "object") return created;
  const incomplete = (error: string) => ({ ...(created as object), uuid: null, identity: "incomplete", uuid_error: error, identity_note: "The entity WAS created but has no UUID yet. Do not recreate it; run taiga_uuid_initialize_project (dry_run=false) for this project to repair the identity." }) as T;
  if (typeof e.id !== "number" || typeof e.project !== "number") return incomplete("the creation response carries no numeric id/project, so the identity could not be assigned");
  try {
    const r = await ensureUuid(client, kind, { id: e.id, project: e.project });
    return r.uuid ? ({ ...(created as object), uuid: r.uuid, identity: "complete" } as T) : incomplete("existing UUID value is not a valid UUIDv7 and was not overwritten");
  } catch (err) {
    return incomplete(err instanceof Error ? err.message : String(err));
  }
}

// Guard for the generic custom-attribute tools: the UUID attribute can be neither redefined nor written through them.
export async function isUuidDefinition(client: TaigaClient, kind: IdentityKind, definitionId: number): Promise<boolean> {
  const d = (await client.get(`/${IDENTITY[kind].definitions}/${definitionId}`)) as Definition;
  return isReservedName(d?.name);
}
// Value updates through the generic tool: the UUID value can neither be written nor dropped. Returns a refusal reason, or the body to send
// (with the entity's current UUID merged back in, so that an update that merely omits the key can never erase it whatever Taiga does with
// a partial map).
export async function guardUuidValues(client: TaigaClient, kind: IdentityKind, entityId: number, values: Record<string, string>): Promise<{ refuse: string } | { values: Record<string, string> }> {
  const e = (await client.get(`/${IDENTITY[kind].entities}/${entityId}`)) as { project?: number };
  if (typeof e.project !== "number") return { values };
  const attr = await uuidAttributeId(client, kind, e.project, false);
  if (attr === undefined) return { values };
  if (Object.keys(values).includes(String(attr))) return { refuse: "writing its value" };
  const current = ((await client.get(`/${IDENTITY[kind].values}/${entityId}`)) as { attributes_values?: Record<string, string> }).attributes_values?.[String(attr)];
  return { values: current ? { ...values, [String(attr)]: current } : values };
}

export interface KindReport {
  kind: IdentityKind;
  attribute: { exists: boolean; created: boolean; would_create: boolean; integrity_error?: string };
  scanned: number; already: number; to_assign: number; assigned: number; invalid_existing: number[]; failed: { id: number; error: string }[];
  /** Entities still without a valid UUID in the FINAL read-only verification (0 when the kind is complete). */
  to_assign_after: number;
  uuid_ready: boolean;
}
// `uuid_ready` is a PROJECT property: it exists as true only when all four supported kinds were covered and the FINAL verification found
// every entity holding a valid, unique UUIDv7. A partial selection (deprecated alias only) reports `partial: true`, `uuid_ready: false`
// and the readiness of the selection in `selected_kinds_ready`.
export interface InitializeReport { project: number; dry_run: boolean; uuid_ready: boolean; partial: boolean; selected_kinds_ready: boolean; duplicate_uuids: { uuid: string; entities: { kind: IdentityKind; id: number }[] }[]; kinds: KindReport[] }
const ALL_KINDS: IdentityKind[] = ["epic", "userstory", "task", "issue"];

interface Scan { scanned: number; valid: { id: number; uuid: string }[]; missing: number[]; invalid: number[]; failed: { id: number; error: string }[] }

// Read-only observation of every entity of a kind: the single source of what is "valid", "missing" or "invalid". Readiness is only ever
// derived from a Scan, never from counters of what a write was supposed to do.
async function scanKind(client: TaigaClient, project: number, kind: IdentityKind, attr: number | undefined): Promise<Scan> {
  const out: Scan = { scanned: 0, valid: [], missing: [], invalid: [], failed: [] };
  const rows = (await client.getAll(`/${IDENTITY[kind].entities}`, { project })) as { id: number }[];
  if (!Array.isArray(rows)) { out.failed.push({ id: 0, error: "the entity list response was not a list" }); return out; }
  for (const row of rows) {
    out.scanned++;
    try {
      const vals = attr === undefined ? null : ((await client.get(`/${IDENTITY[kind].values}/${row.id}`)) as { attributes_values?: Record<string, string> });
      const v = vals?.attributes_values?.[String(attr)];
      if (!v) out.missing.push(row.id);
      else if (UUID_RE.test(v)) out.valid.push({ id: row.id, uuid: v });
      else out.invalid.push(row.id);
    } catch (e) { out.failed.push({ id: row.id, error: e instanceof Error ? e.message : String(e) }); }
  }
  return out;
}

// The one canonical project operation: make the project UUID-ready for Task, User Story, Epic and Issue. Defines the `UUID` attribute where
// missing and fills every entity that has none. Dry run (default) only reports. Valid UUIDv7 values are never changed and invalid existing
// values are only reported. After writing, a second read-only scan verifies the result; that scan (plus project-wide uniqueness) is the
// only basis of `uuid_ready`. Idempotent: on a ready project it writes nothing.
export async function initializeProject(client: TaigaClient, project: number, opts: { dryRun?: boolean; kinds?: IdentityKind[] } = {}): Promise<InitializeReport> {
  const dryRun = opts.dryRun !== false;
  const kinds: KindReport[] = [];
  const finalValid: { kind: IdentityKind; id: number; uuid: string }[] = [];
  for (const kind of opts.kinds ?? ALL_KINDS) {
    const r: KindReport = { kind, attribute: { exists: false, created: false, would_create: false }, scanned: 0, already: 0, to_assign: 0, assigned: 0, invalid_existing: [], failed: [], to_assign_after: 0, uuid_ready: false };
    let attr: number | undefined;
    try {
      attr = await uuidAttributeId(client, kind, project, false);
      r.attribute.exists = attr !== undefined;
      if (attr === undefined) {
        if (dryRun) r.attribute.would_create = true;
        else { attr = await uuidAttributeId(client, kind, project, true); r.attribute.created = attr !== undefined; }
      }
    } catch (e) {
      const msg = e instanceof Error ? e.message : String(e);
      if (e instanceof IdentityIntegrityError) r.attribute.integrity_error = msg;
      r.failed.push({ id: 0, error: `attribute definition: ${msg}` }); kinds.push(r); continue;
    }
    let final: Scan;
    try {
      const first = await scanKind(client, project, kind, attr);
      r.scanned = first.scanned; r.already = first.valid.length; r.to_assign = first.missing.length; r.invalid_existing = [...first.invalid];
      final = first;
      if (!dryRun && first.missing.length > 0) {
        for (const id of first.missing) {
          try { if ((await ensureUuid(client, kind, { id, project })).assigned) r.assigned++; }
          catch (e) { r.failed.push({ id, error: e instanceof Error ? e.message : String(e) }); }
        }
        // Verification: re-resolve the single definition and re-read everything. Readiness is judged on THIS observation only.
        if ((await uuidAttributeId(client, kind, project, false)) !== attr) throw new IdentityIntegrityError(`integrity error: the "${UUID_ATTRIBUTE}" definition for ${kind} in project ${project} changed during initialization`);
        final = await scanKind(client, project, kind, attr);
      }
    } catch (e) {
      const msg = e instanceof Error ? e.message : String(e);
      if (e instanceof IdentityIntegrityError) r.attribute.integrity_error = msg;
      r.failed.push({ id: 0, error: msg }); kinds.push(r); continue;
    }
    r.failed.push(...final.failed); // scan failures of the FINAL observation only (no double counting)
    r.to_assign_after = final.missing.length;
    r.invalid_existing = [...new Set([...r.invalid_existing, ...final.invalid])];
    finalValid.push(...final.valid.map((v) => ({ kind, ...v })));
    r.uuid_ready = (r.attribute.exists || r.attribute.created) && final.missing.length === 0 && final.invalid.length === 0 && final.failed.length === 0 && r.failed.length === 0 && r.invalid_existing.length === 0;
    kinds.push(r);
  }
  // Uniqueness is judged on the verified values of every covered kind: the same UUID on two entities is corruption (reported, never "fixed").
  const byUuid = new Map<string, { kind: IdentityKind; id: number }[]>();
  for (const v of finalValid) byUuid.set(v.uuid.toLowerCase(), [...(byUuid.get(v.uuid.toLowerCase()) ?? []), { kind: v.kind, id: v.id }]);
  const duplicate_uuids = [...byUuid].filter(([, v]) => v.length > 1).map(([uuid, entities]) => ({ uuid, entities }));
  const selectedReady = kinds.length > 0 && kinds.every((k) => k.uuid_ready) && duplicate_uuids.length === 0;
  const partial = !ALL_KINDS.every((k) => kinds.some((x) => x.kind === k));
  return { project, dry_run: dryRun, uuid_ready: !partial && selectedReady, partial, selected_kinds_ready: selectedReady, duplicate_uuids, kinds };
}

export interface ResolvedEntity { uuid: string; type: IdentityKind; project: number; id: number; ref: number | null; subject: string | null }
export type Resolution =
  | { status: "found"; entity: ResolvedEntity; scanned: number; scope: string; kinds_without_attribute: string[] }
  | { status: "not_found"; uuid: string; scanned: number; scope: string; kinds_without_attribute: string[] }
  | { status: "duplicate"; uuid: string; matches: ResolvedEntity[]; scanned: number; scope: string }
  | { status: "invalid_uuid"; uuid: string }
  | { status: "integrity_error"; uuid: string; message: string };

// UUID -> entity. Taiga cannot filter by custom attribute, so this scans the entities of the given project (or every visible project) and
// compares the stored value; the UUID is authoritative, `ref` is only reported. Several matches is a closed failure, never a silent pick.
export async function resolveUuid(client: TaigaClient, uuid: string, scope: { project?: number; kinds?: IdentityKind[] } = {}): Promise<Resolution> {
  const wanted = uuid.trim().toLowerCase();
  if (!UUID_RE.test(wanted)) return { status: "invalid_uuid", uuid };
  const projects = scope.project !== undefined ? [scope.project] : await allProjects(client);
  const scopeLabel = scope.project !== undefined ? `project ${scope.project}` : "all visible projects";
  const matches: ResolvedEntity[] = [];
  const noAttr = new Set<string>();
  let scanned = 0;
  for (const project of projects) {
    for (const kind of scope.kinds ?? (["epic", "userstory", "task", "issue"] as IdentityKind[])) {
      let attr: number | undefined;
      try { attr = await uuidAttributeId(client, kind, project, false); } catch (e) { if (e instanceof IdentityIntegrityError) return { status: "integrity_error", uuid: wanted, message: e.message }; throw e; }
      if (attr === undefined) { noAttr.add(`${kind}@${project}`); continue; }
      const rows = (await client.getAll(`/${IDENTITY[kind].entities}`, { project })) as { id: number; ref?: number; subject?: string }[];
      if (!Array.isArray(rows)) throw new Error(`the ${kind} list of project ${project} was not a list`);
      for (const row of rows) {
        scanned++;
        const v = ((await client.get(`/${IDENTITY[kind].values}/${row.id}`)) as { attributes_values?: Record<string, string> }).attributes_values?.[String(attr)];
        if (typeof v === "string" && v.toLowerCase() === wanted) matches.push({ uuid: wanted, type: kind, project, id: row.id, ref: row.ref ?? null, subject: row.subject ?? null });
      }
    }
  }
  const kinds_without_attribute = [...noAttr];
  if (matches.length === 0) return { status: "not_found", uuid: wanted, scanned, scope: scopeLabel, kinds_without_attribute };
  if (matches.length > 1) return { status: "duplicate", uuid: wanted, matches, scanned, scope: scopeLabel };
  return { status: "found", entity: matches[0], scanned, scope: scopeLabel, kinds_without_attribute };
}

async function allProjects(client: TaigaClient): Promise<number[]> {
  const rows = (await client.getAll("/projects")) as { id: number }[];
  if (!Array.isArray(rows)) throw new Error("the project list was not a list");
  return rows.map((r) => r.id);
}
