// Generates src/policy/operations.ts: every registered tool as an operation with its access, scope and rule. The runtime registry is the
// source (never a hand-kept list), so a tool added without being classified shows up as a diff and fails the drift test.
//   node scripts/policy-catalog.ts --write
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { toolInventory } from "./tools-inventory.ts";

type Tool = Awaited<ReturnType<typeof toolInventory>>[number];
export const OPERATIONS_PATH = fileURLToPath(new URL("../src/policy/operations.ts", import.meta.url));

// Tools about no project at all: the instance, the caller, or a person.
const GLOBAL = new Set(["taiga_governance_status", "taiga_projects_create", "taiga_project_import", "taiga_projects_get_by_slug", "taiga_projects_list", "taiga_timeline_profile", "taiga_timeline_user", "taiga_users_me", "taiga_workflow_template"]);
// Where the resource id is when the tool does not call it `id`.
const RESOURCE_PARAM: Record<string, string> = {
  taiga_assignees_backfill: "milestone", taiga_human_decision_resolve: "task_id", taiga_webhooklogs_list: "webhook",
  taiga_workflow_request_answer: "task_id", taiga_workflow_request_create: "task_id",
};
// Rules: workflow = the governed lifecycle; bootstrap = creates or imports a project (global policy, no project yet); baseline = today's
// behavior kept as it is (permissive), recorded so nothing is classified by accident.
const WORKFLOW = new Set(["taiga_workflow_transition", "taiga_workflow_request_create", "taiga_workflow_request_answer", "taiga_human_decision_resolve", "taiga_milestones_prepare_close", "taiga_milestones_confirm_merge", "taiga_milestones_close"]);
const BOOTSTRAP = new Set(["taiga_projects_create", "taiga_project_import"]);

function scopeOf(t: Tool): string {
  if (GLOBAL.has(t.name)) return `{ kind: "global" }`;
  const resource = RESOURCE_PARAM[t.name] ?? (t.name.startsWith("taiga_epics_related_userstories_") ? "epic_id" : t.params.includes("id") ? "id" : undefined);
  if (resource) return `{ kind: "resource", param: "${resource}" }`;
  const project = t.params.includes("project") ? "project" : t.params.includes("project_id") ? "project_id" : undefined;
  if (project) return `{ kind: "project", param: "${project}"${t.required.includes(project) ? "" : ", optional: true"} }`;
  throw new Error(`${t.name}: no scope can be derived from its parameters (${t.params.join(", ")}); classify it in scripts/policy-catalog.ts`);
}

export async function renderOperations(): Promise<string> {
  const rows = (await toolInventory()).map((t) => {
    const rule = WORKFLOW.has(t.name) ? "workflow" : BOOTSTRAP.has(t.name) ? "bootstrap" : "baseline";
    return `  { id: "${t.name}", access: "${t.mutating ? "write" : "read"}", scope: ${scopeOf(t)}, rule: "${rule}" },`;
  });
  return `// GENERATED by scripts/policy-catalog.ts from the runtime tool registry. Do not edit by hand: regenerate with
//   node scripts/policy-catalog.ts --write
import type { Operation } from "./catalog.js";

export const OPERATIONS: readonly Operation[] = [
${rows.join("\n")}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url) && process.argv.includes("--write")) {
  writeFileSync(OPERATIONS_PATH, await renderOperations());
  console.log(`wrote ${OPERATIONS_PATH}`);
}
